#!/usr/bin/env python3
"""Regenerate the live progress block and badge in README.md.

Progress is read from the milestone checkboxes in GOALS.md and the phase
checkboxes in docs/roadmap.md. The generated region is intentionally the only
part of the README this script touches.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GOALS_PATH = ROOT / "GOALS.md"
ROADMAP_PATH = ROOT / "docs" / "roadmap.md"
README_PATH = ROOT / "README.md"

START = "<!-- progress:start -->"
END = "<!-- progress:end -->"
BADGE_MARKER = "<!-- progress-badge -->"
BAR_WIDTH = 10

GOAL_HEADING = re.compile(r"^## (?P<id>G\d+) — (?P<title>.+?)\s*$")
PHASE_HEADING = re.compile(r"^## (?P<id>Phase \d+) — (?P<title>[^()]+?)(?: \([^)]*\))?\s*$")
CHECKBOX = re.compile(r"^\s*[-*] \[(?P<mark>[ xX])\]\s+(?P<text>.+?)\s*$")


@dataclass
class Track:
    """A goal or phase with its checked and total milestone counts."""

    id: str
    title: str
    done: int = 0
    total: int = 0

    @property
    def percent(self) -> int:
        if self.total == 0:
            return 0
        return round(100 * self.done / self.total)


def parse_tracks(path: Path, heading: re.Pattern[str]) -> list[Track]:
    """Parse checkbox counts for each matching section heading in *path*."""
    tracks: list[Track] = []
    current: Track | None = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            match = heading.match(line)
            current = Track(match.group("id"), match.group("title").strip()) if match else None
            if current is not None:
                tracks.append(current)
            continue
        if current is None:
            continue
        match = CHECKBOX.match(line)
        if match:
            current.total += 1
            if match.group("mark").lower() == "x":
                current.done += 1
    return tracks


def bar(percent: int) -> str:
    """Render a fixed-width text progress bar."""
    filled = round(percent * BAR_WIDTH / 100)
    return "█" * filled + "░" * (BAR_WIDTH - filled)


def anchor(text: str) -> str:
    """Approximate the GitHub heading anchor for *text*."""
    slug = re.sub(r"[^\w\s-]", "", text.lower())
    return slug.replace(" ", "-")


def overall(tracks: list[Track]) -> Track:
    done = sum(track.done for track in tracks)
    total = sum(track.total for track in tracks)
    return Track("Overall", "Overall", done, total)


def render_block(goals: list[Track], phases: list[Track]) -> str:
    """Render the markdown tables inserted into README.md."""
    totals = overall(goals)
    lines = [
        "<!-- Generated by scripts/update_progress.py from GOALS.md and "
        "docs/roadmap.md. Do not edit by hand. -->",
        "",
        "| Goal | Progress | Milestones |",
        "|---|---|---:|",
    ]
    for goal in goals:
        link = f"[{goal.id} — {goal.title}](GOALS.md#{anchor(f'{goal.id} — {goal.title}')})"
        ratio = f"{goal.done}/{goal.total}" if goal.total else "—"
        lines.append(f"| {link} | `{bar(goal.percent)}` {goal.percent}% | {ratio} |")
    lines.append(
        f"| **{totals.id}** | `{bar(totals.percent)}` {totals.percent}% | "
        f"{totals.done}/{totals.total} |"
    )
    lines.extend(["", "| Roadmap phase | Progress | Items |", "|---|---|---:|"])
    for phase in phases:
        ratio = f"{phase.done}/{phase.total}" if phase.total else "—"
        lines.append(
            f"| {phase.id} — {phase.title} | `{bar(phase.percent)}` {phase.percent}% | {ratio} |"
        )
    return "\n".join(lines)


def badge_line(percent: int) -> str:
    """Render the shields.io progress badge line."""
    color = "brightgreen" if percent == 100 else "yellow"
    url = f"https://img.shields.io/badge/progress-{percent}%25-{color}.svg"
    return f"[![Progress]({url})](#goals-and-live-progress) {BADGE_MARKER}"


def replace_block(text: str, block: str) -> str:
    """Replace the region between the progress markers."""
    start = text.find(START)
    end = text.find(END, start + 1)
    if start == -1 or end == -1:
        raise ValueError(f"README.md is missing {START} or {END}")
    return f"{text[: start + len(START)]}\n{block}\n{text[end:]}"


def replace_badge(text: str, percent: int) -> str:
    """Replace the line carrying the badge marker."""
    lines = text.splitlines(keepends=True)
    for index, line in enumerate(lines):
        if BADGE_MARKER in line:
            lines[index] = badge_line(percent) + ("\n" if line.endswith("\n") else "")
            return "".join(lines)
    raise ValueError(f"README.md is missing the {BADGE_MARKER} line")


def build() -> tuple[str, str, Track]:
    """Return the current README text, the regenerated text, and the goal totals."""
    goals = parse_tracks(GOALS_PATH, GOAL_HEADING)
    phases = parse_tracks(ROADMAP_PATH, PHASE_HEADING)
    if not goals:
        raise ValueError(f"no goal checkboxes found in {GOALS_PATH}")
    if not phases:
        raise ValueError(f"no phase checkboxes found in {ROADMAP_PATH}")

    totals = overall(goals)
    readme = README_PATH.read_text(encoding="utf-8")
    updated = replace_badge(replace_block(readme, render_block(goals, phases)), totals.percent)
    return readme, updated, totals


def main(argv: list[str] | None = None) -> int:
    """Update README.md, or verify it with ``--check``."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if README.md progress is stale instead of writing it",
    )
    parser.add_argument(
        "--stdout",
        action="store_true",
        help="print the generated block instead of writing README.md",
    )
    args = parser.parse_args(argv)

    try:
        readme, updated, totals = build()
    except (OSError, ValueError) as exc:
        print(f"progress error: {exc}", file=sys.stderr)
        return 2

    if args.stdout:
        print(updated)
        return 0

    summary = f"{totals.done}/{totals.total} milestones ({totals.percent}%)"

    if args.check:
        if readme != updated:
            print(
                "README.md progress is stale; run: python scripts/update_progress.py",
                file=sys.stderr,
            )
            return 1
        print(f"README.md progress is up to date ({summary})")
        return 0

    if readme == updated:
        print(f"README.md progress is up to date ({summary})")
        return 0

    README_PATH.write_text(updated, encoding="utf-8")
    print(f"updated README.md ({summary})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
